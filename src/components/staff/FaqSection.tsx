function FaqScreenshot({ id, isKy }: { id: string; isKy?: boolean }) {
  const [broken, setBroken] = useState(false);

  if (broken) {
    return (
      <div className="mt-3 flex items-center gap-2 rounded-lg border border-dashed border-slate-200 bg-slate-50 px-3 py-2 text-xs text-slate-400">
        <ImageOff className="h-3.5 w-3.5" />
        {isKy ? "Скриншот кийинчерээк кошулат" : "Скриншот появится позже"}
      </div>
    );
  }

  return (
    // eslint-disable-next-line @next/next/no-img-element -- статичный файл из public/faq, не требует next/image
    <img
      src={faqScreenshotSrc(id)}
      alt=""
      className="mt-3 w-full rounded-lg border border-slate-200"
      onError={() => setBroken(true)}
    />
  );
}

export function FaqSection({
  isKy,
  defaultRole,
}: {
  isKy?: boolean;
  defaultRole?: FaqRole;
}) {
  const [open, setOpen] = useState(false);
  const [activeRole, setActiveRole] = useState<FaqRole>(defaultRole ?? "reception");
  const L = (ru: string, ky: string) => (isKy ? ky : ru);

  return (
    <div className="rounded-xl border border-slate-200 bg-white shadow-sm">
      <div className="flex flex-wrap items-center justify-between gap-3 px-4 py-3.5 sm:px-5">
        <div className="flex items-start gap-2.5">
          <HelpCircle className="mt-0.5 h-5 w-5 shrink-0 text-court-blue" />
          <div>
            <div className="text-sm font-semibold text-slate-900 sm:text-base">
              {L("Часто задаваемые вопросы", "Көп берилген суроолор")}
            </div>
            <p className="mt-0.5 text-xs text-slate-500 sm:text-sm">
              {L(
                "Пошаговые ответы по разделам — отдельно для каждой роли.",
                "Ролго жараша кадам-кадам жооптор."
              )}
            </p>
          </div>
        </div>
        <button
          type="button"
          onClick={() => setOpen((v) => !v)}
          className={open ? "btn-outline !text-sm" : "btn-primary !text-sm"}
        >
          {open ? L("Скрыть", "Жашыруу") : L("Подробнее", "Кененирээк")}
        </button>
      </div>

      {open && (
        <div className="border-t border-slate-100 px-4 py-4 sm:px-5">
          <div className="mb-4 flex flex-wrap gap-1.5">
            {ROLE_TABS.map((tab) => (
              <button
                key={tab.role}
                type="button"
                onClick={() => setActiveRole(tab.role)}
                className={cn(
                  "rounded-full border px-3 py-1.5 text-xs font-semibold transition",
                  activeRole === tab.role
                    ? "border-court-navy bg-court-navy text-white"
                    : "border-slate-200 bg-white text-slate-600 hover:bg-slate-50"
                )}
              >
                {isKy ? tab.ky : tab.ru}
              </button>
            ))}
          </div>

          <div className="space-y-2.5">
            {FAQ_BY_ROLE[activeRole].map((item) => (
              <Collapsible
                key={item.id}
                title={isKy ? item.qKy : item.qRu}
                className="shadow-none"
              >
                <ol className="list-decimal space-y-1.5 pl-5 text-sm text-slate-700">
                  {(isKy ? item.stepsKy : item.stepsRu).map((step, i) => (
                    <li key={i}>{step}</li>
                  ))}
                </ol>
                <FaqScreenshot id={item.id} isKy={isKy} />
              </Collapsible>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
